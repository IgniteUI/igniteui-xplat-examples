// The keys stay as the C# and TypeScript spell them: a data item defined in
// code keeps its own casing across platforms, and these are the names the
// member paths in the descriptions ask for.
class StockItem implements IReflectable, IReflectableSet {
    double? open = null;
    double? close = null;
    double? high = null;
    double? low = null;
    double? volume = null;
    DateTime? date = null;

    Object? getValue(String? propertyName) {
        switch (propertyName) {
            case "Open":
                return this.open;
            case "Close":
                return this.close;
            case "High":
                return this.high;
            case "Low":
                return this.low;
            case "Volume":
                return this.volume;
            case "Date":
                return this.date;
        }
        return null;
    }

    void setValue(String? propertyName, Object? value) {
        switch (propertyName) {
            case "Open":
                this.open = (value as num?)?.toDouble();
                break;
            case "Close":
                this.close = (value as num?)?.toDouble();
                break;
            case "High":
                this.high = (value as num?)?.toDouble();
                break;
            case "Low":
                this.low = (value as num?)?.toDouble();
                break;
            case "Volume":
                this.volume = (value as num?)?.toDouble();
                break;
            case "Date":
                this.date = value as DateTime?;
                break;
        }
    }
}

